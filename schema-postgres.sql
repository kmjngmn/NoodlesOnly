-- Private schema: the Supabase public REST API must not expose member codes.
CREATE SCHEMA IF NOT EXISTS study_app;
REVOKE ALL ON SCHEMA study_app FROM PUBLIC;
SET LOCAL search_path = study_app;

CREATE TABLE IF NOT EXISTS members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname TEXT NOT NULL,
    code TEXT NOT NULL UNIQUE,
    joined_on TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS members_nickname_unique ON members (lower(nickname));

CREATE TABLE IF NOT EXISTS submissions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id INTEGER NOT NULL REFERENCES members(id),
    day TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('approved', 'pending', 'rejected')),
    reason TEXT NOT NULL DEFAULT '',
    photo TEXT,
    photo_hash TEXT,
    submitted_at TEXT NOT NULL,
    expires_on TEXT,
    UNIQUE (member_id, day)
);

CREATE TABLE IF NOT EXISTS rests (
    member_id INTEGER NOT NULL REFERENCES members(id),
    week TEXT NOT NULL,
    day TEXT NOT NULL,
    PRIMARY KEY (member_id, week)
);

CREATE TABLE IF NOT EXISTS payments (
    member_id INTEGER NOT NULL REFERENCES members(id),
    week TEXT NOT NULL,
    amount INTEGER NOT NULL,
    paid_at TEXT NOT NULL,
    PRIMARY KEY (member_id, week)
);

CREATE TABLE IF NOT EXISTS attempts (bucket TEXT NOT NULL, at DOUBLE PRECISION NOT NULL);
CREATE INDEX IF NOT EXISTS attempt_bucket ON attempts (bucket, at);

-- Track every allocated photo independently, including failed or abandoned uploads.
CREATE TABLE IF NOT EXISTS photo_objects (
    photo TEXT PRIMARY KEY,
    expires_on TEXT NOT NULL
);
